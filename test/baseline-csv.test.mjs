test("baseline module Worker transfers ArrayBuffer, retains state, clears it, and classifies task errors", async () => {
  const previousSelf = globalThis.self;
  const listeners = new Map();
  const posted = [];
  globalThis.self = {
    addEventListener(type, callback) {
      listeners.set(type, callback);
    },
    postMessage(message, transfer = []) {
      posted.push({ message, transfer });
    },
  };
  try {
    await import(`../public/csv-worker.js?baseline=${Date.now()}`);
    const source = new Uint8Array(await readFile(new URL("resolve-source.csv", csvRoot)));
    listeners.get("message")({ data: { id: 1, task: { type: "decode-metadata", data: source } } });
    listeners.get("message")({ data: {
      id: 2,
      task: {
        type: "export-resolve",
        records: [{ cardNumber: "A001", videoCode: "C001", scene: "1", shot: "2", take: "3", takeStatus: "过" }],
        fieldFormats: { scene: "XXX", shot: "XX", take: "XX" },
        comments: { goodTake: "_OK", holdTake: "_KP" },
      },
    } });
    const transferred = posted.find((entry) => entry.message.id === 2);
    assert.ok(transferred.message.result.bytes instanceof ArrayBuffer);
    assert.equal(transferred.transfer[0], transferred.message.result.bytes);

    listeners.get("message")({ data: { id: 3, task: { type: "clear-metadata" } } });
    listeners.get("message")({ data: { id: 4, task: { type: "export-resolve", records: [] } } });
    assert.match(posted.find((entry) => entry.message.id === 4).message.error, /尚未载入有效的 Resolve CSV/);
  } finally {
    if (previousSelf === undefined) delete globalThis.self;
    else globalThis.self = previousSelf;
  }
});

test("baseline Worker client handles transfer, task errors, termination, and infrastructure-only fallback", async () => {
  let instance;
  class FakeWorker {
    constructor() {
      instance = this;
      this.listeners = new Map();
    }
    addEventListener(type, callback) { this.listeners.set(type, callback); }
    postMessage(message, transfer) { this.posted = { message, transfer }; }
    terminate() { this.terminated = true; }
  }

  const client = createCsvWorkerClient({ WorkerClass: FakeWorker });
  const buffer = new ArrayBuffer(4);
  const success = client.request({ type: "prime-metadata" }, [buffer]);
  instance.listeners.get("message")({ data: { id: 1, result: { ready: true } } });
  assert.deepEqual(await success, { ready: true });
  assert.equal(instance.posted.transfer[0], buffer);

  const taskFailure = client.request({ type: "unknown" });
  instance.listeners.get("message")({ data: { id: 2, error: "synthetic task error" } });
  await assert.rejects(taskFailure, (error) => error.csvWorkerTask === true && /synthetic task error/.test(error.message));

  const pending = client.request({ type: "decode-metadata" });
  client.terminate();
  await assert.rejects(pending, /CSV 后台 Worker 已停止/);
  assert.equal(instance.terminated, true);
  assert.equal(createCsvWorkerClient({ WorkerClass: null }), null);
  assert.equal(createCsvWorkerClient({ WorkerClass: class { constructor() { throw new Error("blocked"); } } }), null);
});

test("baseline typed-array subviews save only their exact byte range", async () => {
  const previous = globalThis.electronAPI;
  let saved;
  globalThis.electronAPI = {
    saveFile: async (_filename, data) => {
      saved = new Uint8Array(data);
      return { saved: true };
    },
  };
  try {
    const backing = new Uint8Array([9, 1, 2, 3, 8]);
    await downloadFileApi(backing.subarray(1, 4), "exact.csv");
    assert.deepEqual([...saved], [1, 2, 3]);
  } finally {
    if (previous === undefined) delete globalThis.electronAPI;
    else globalThis.electronAPI = previous;
  }
});
