test("baseline standalone export has exact UTF-16LE CRLF bytes and skips incomplete records", () => {
  const processTask = createCsvTaskProcessor();
  const output = processTask({
    type: "export-standalone",
    records: [
      { cardNumber: "A001", videoCode: "C001", scene: "37a", shot: "2", take: "11", comments: "HOLD" },
      { cardNumber: "A001", videoCode: "C002", scene: "1234", shot: "100", take: "3", comments: "YES" },
      { cardNumber: "A001", videoCode: "C003", scene: null, shot: "1", take: "1" },
    ],
    fieldFormats: { scene: "XXX", shot: "XX", take: "XX" },
    comments: { goodTake: "YES", holdTake: "HOLD" },
  });
  const expected = manifest.outputs.standalone;
  assertBytes(output.bytes, expected);
  const text = new TextDecoder("utf-16le").decode(output.bytes.subarray(2));
  const matrix = parseCsvText(text, expected.format.delimiter);
  assert.deepEqual(matrix[0], expected.headers);
  assert.deepEqual(matrix.slice(1), expected.rows);
  assert.equal(text.includes("\r\n"), true);
});

