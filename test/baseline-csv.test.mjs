// The reviewed manifest is deliberately independent of production constants:
// generated bytes are compared to fixed length/hash/table evidence and are
// never written back by the tests.
const csvRoot = new URL("./fixtures/baseline/csv/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json", csvRoot), "utf8"));

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function assertBytes(bytes, expected) {
  assert.equal(bytes.byteLength, expected.bytes, "CSV byte length drift");
  assert.equal(sha256(bytes), expected.sha256, "CSV SHA-256 drift");
}

function assertResolveTable(bytes, expected) {
  assertBytes(bytes, expected);
  const table = decodeResolveCsv(bytes);
  assert.deepEqual(table.format, expected.format);
  assert.deepEqual(table.headers, expected.headers);
  assert.deepEqual(table.rows, expected.rows);
  return table;
}

test("baseline source fixtures and round-trip bytes match the reviewed manifest", async () => {
  for (const [name, expected] of Object.entries(manifest.sources)) {
    const bytes = new Uint8Array(await readFile(new URL(name, csvRoot)));
    const table = assertResolveTable(bytes, expected);
    const roundTrip = encodeResolveCsv(table);
    assertBytes(roundTrip, expected.roundTrip);
  }
});

test("a deliberate one-byte mutation fails the reviewed CSV byte contract", async () => {
  const expected = manifest.sources["resolve-source.csv"];
  const bytes = new Uint8Array(await readFile(new URL("resolve-source.csv", csvRoot)));
  const mutated = bytes.slice();
  mutated[Math.floor(mutated.length / 2)] ^= 1;
  assert.notEqual(sha256(mutated), expected.sha256);
  assert.throws(() => assertBytes(mutated, expected), /CSV SHA-256 drift/);
});

